// Suggestions for a text box: matches however it's typed ("B Co 1-32", "1-32/B",
// "bravo company 1-32", "1-32 infantry" all find "1-32 B Co" / "1-32 INF").
(function () {
  const SAME = { infantry: "in", inf: "in", company: "co", battalion: "bn", brigade: "bde", battery: "btry", troop: "trp", squadron: "sqdn",
    cavalry: "cav", aviation: "avn", engineer: "en", engineers: "en", engineering: "en", eng: "en", "field artillery": "fa", artillery: "fa",
    "military police": "mp", police: "mp", "military intelligence": "mi", intelligence: "mi", signal: "sig", sustainment: "sust",
    headquarters: "hq", detachment: "det", regiment: "rgt", regt: "rgt", division: "div", mountain: "mtn", medical: "med",
    alpha: "a", bravo: "b", charlie: "c", delta: "d", echo: "e", foxtrot: "f", golf: "g", hotel: "h" };
  const words = s => {
    let t = " " + String(s).toLowerCase().replace(/[^a-z0-9]+/g, " ") + " ";
    for (const [k, v] of Object.entries(SAME)) if (k.includes(" ")) t = t.split(" " + k + " ").join(" " + v + " ");
    return t.trim().split(" ").filter(Boolean).map(w => SAME[w] || w.replace(/(\d+)(st|nd|rd|th|d)$/, "$1"));
  };
  const index = (window.UNITS || []).map(u => ({ u, w: words(u) }));
  function find(q) {
    const want = words(q);
    if (!want.length) return [];
    return index.filter(x => want.every(t => x.w.some(w => w === t || (t.length > 1 && w.startsWith(t)))))
      .sort((a, b) => a.w.length - b.w.length).slice(0, 8).map(x => x.u);
  }

  if (!document.getElementById("unit-style")) {
    const st = document.createElement("style");
    st.id = "unit-style";
    st.textContent = `
      .unit-wrap { position: relative; }
      .unit-list { position: absolute; z-index: 30; left: 0; right: 0; top: calc(100% + 4px); margin: 0; padding: 6px; list-style: none; max-height: 300px; overflow: auto;
        background: #fff; color: #1a0f13; border: 2px solid #000; border-radius: 12px; box-shadow: 0 12px 30px rgba(0,0,0,.35); }
      .unit-list li { padding: 8px 10px; border-radius: 8px; cursor: pointer; }
      .unit-list li[aria-selected="true"], .unit-list li:hover { background: #f9e4eb; }
      .unit-list .unit-hint { cursor: default; color: #6b5a60; font-size: .85rem; }
      .unit-list .unit-hint:hover { background: none; }`;
    document.head.appendChild(st);
  }

  window.attachUnitSuggest = function (input) {
    if (!input || input.dataset.units) return;
    input.dataset.units = "1";
    input.setAttribute("autocomplete", "off");
    input.setAttribute("role", "combobox");
    input.setAttribute("aria-autocomplete", "list");
    input.setAttribute("aria-expanded", "false");
    const wrap = document.createElement("div");
    wrap.className = "unit-wrap";
    input.parentNode.insertBefore(wrap, input);
    wrap.appendChild(input);
    const list = document.createElement("ul");
    list.className = "unit-list";
    list.id = input.id + "-units";
    list.setAttribute("role", "listbox");
    list.hidden = true;
    input.setAttribute("aria-controls", list.id);
    wrap.appendChild(list);
    let items = [], active = -1;
    const close = () => { list.hidden = true; list.innerHTML = ""; input.setAttribute("aria-expanded", "false"); active = -1; };
    const pick = i => { const v = items[i]; close(); input.value = v; input.dispatchEvent(new Event("input", { bubbles: true })); };
    function show() {
      list.innerHTML = "";
      items.forEach((u, i) => {
        const li = document.createElement("li");
        li.setAttribute("role", "option");
        li.id = `${list.id}-${i}`;
        li.setAttribute("aria-selected", i === active);
        li.textContent = u;
        li.onmousedown = e => { e.preventDefault(); pick(i); };
        list.appendChild(li);
      });
      const hint = document.createElement("li");
      hint.className = "unit-hint";
      hint.textContent = "Not listed? Just type it the way it should read.";
      list.appendChild(hint);
      list.hidden = false;
      input.setAttribute("aria-expanded", "true");
    }
    input.addEventListener("input", e => {
      if (!e.isTrusted) return;
      items = input.value.trim().length >= 2 ? find(input.value) : [];
      active = -1;
      if (items.length) show(); else close();
    });
    input.addEventListener("keydown", e => {
      if (list.hidden || !items.length) return;
      if (e.key === "ArrowDown" || e.key === "ArrowUp") {
        e.preventDefault();
        active = (active + (e.key === "ArrowDown" ? 1 : -1) + items.length) % items.length;
        [...list.children].forEach((li, i) => li.setAttribute("aria-selected", i === active));
        input.setAttribute("aria-activedescendant", `${list.id}-${active}`);
      } else if (e.key === "Enter" && active >= 0) { e.preventDefault(); pick(active); }
      else if (e.key === "Escape") close();
    });
    input.addEventListener("blur", () => setTimeout(close, 150));
  };
})();
